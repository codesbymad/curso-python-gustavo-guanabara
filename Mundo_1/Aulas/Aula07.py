s = n1 - n2
m = n1 * n2
d = n1 / n2
p = n1 ** n2
dI = n1 // n2
r = n1 % n2
print(f"A adição é {a}, A subtração é {s}, A multiplicação é {m}, A divisão é {d}, A potência é {p}, A divisão inteira é {dI}, O resto da divisão é {r}")